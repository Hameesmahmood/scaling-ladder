-- The baseline schema: primary keys only, on purpose. Step 1 of the ladder adds the indexes
-- (db/indexes.sql); scripts/db.sh switches between the two.

CREATE TABLE IF NOT EXISTS customers (
    id   bigint PRIMARY KEY,
    name text   NOT NULL
);

CREATE TABLE IF NOT EXISTS shipments (
    id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number text        NOT NULL,
    customer_id     bigint      NOT NULL REFERENCES customers (id),
    service         text        NOT NULL CHECK (service IN ('economy', 'standard', 'express')),
    origin          text        NOT NULL,
    destination     text        NOT NULL,
    status          text        NOT NULL
                    CHECK (status IN ('label_created', 'in_transit', 'out_for_delivery', 'delivered', 'exception')),
    created_at      timestamptz NOT NULL,
    updated_at      timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS tracking_events (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Postgres does not index foreign keys by itself, so this lookup is a full scan until step 1.
    shipment_id bigint      NOT NULL REFERENCES shipments (id),
    occurred_at timestamptz NOT NULL,
    status      text        NOT NULL,
    location    text        NOT NULL
);
